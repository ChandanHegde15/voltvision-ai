"""Generate result tables in docs/EXPERIMENTS.md and README.md from the recorded JSON reports.

No number in those sections is typed by hand. Run after any re-evaluation or
experiment run; use --check to fail when the docs no longer match the reports.
"""
from __future__ import annotations
import argparse
import json
from pathlib import Path
import sys

sys.path.insert(0, str(Path(__file__).resolve().parents[1]))
from config import ARTIFACTS_DIR, REPORTS_DIR, ROOT

EXP = REPORTS_DIR / "experiments"
README = ROOT / "README.md"; EXPERIMENTS_DOC = ROOT / "docs" / "EXPERIMENTS.md"
START, END = "<!-- results:start (generated by scripts/build_docs.py) -->", "<!-- results:end -->"

def load(path: Path) -> dict: return json.loads(path.read_text(encoding="utf-8"))
def f4(x) -> str: return "n/a" if x is None else f"{x:.4f}"
def ms(x) -> str: return f"{x:.1f}"
def cm(m) -> str: return f"`{m}`"
def table(header: list[str], rows: list[list[str]]) -> str:
    return "\n".join(["| " + " | ".join(header) + " |", "|" + "---|" * len(header)] + ["| " + " | ".join(r) + " |" for r in rows])

def readme_section(ev: dict, meta: dict | None, e3: dict) -> str:
    agg = e3["aggregate"]; seeds = e3["seeds"]
    lines = [START, "", "## Results"]
    lines += ["", f"Recorded baseline (`reports/evaluation.json`; reference bank built {(meta or {}).get('created_at_utc', 'n/a')[:10]}, seed {(meta or {}).get('seed', 'n/a')}): "
              f"{ev['evaluated_images']} held-out test images, threshold `{ev['threshold']}`.", "",
              table(["Precision", "Recall", "F1", "ROC-AUC", "Confusion matrix [[TN, FP], [FN, TP]]", "Mean latency (ms)"],
                    [[f4(ev["precision"]), f4(ev["recall"]), f4(ev["f1"]), f4(ev["roc_auc"]), cm(ev["confusion_matrix"]), ms(ev["average_latency_ms"])]])]
    position = "is below the lowest of these splits" if ev["f1"] < agg["f1"]["min"] else "lies within this range"
    lines += ["", f"**Split sensitivity.** Repeating the full protocol over {len(seeds)} other normal reference/validation splits (seeds {seeds[0]}–{seeds[-1]}) gives "
              f"F1 {f4(agg['f1']['mean'])} ± {f4(agg['f1']['std'])} (range {f4(agg['f1']['min'])}–{f4(agg['f1']['max'])}) and recall {f4(agg['recall']['mean'])} ± {f4(agg['recall']['std'])}. "
              f"The seed-{e3['baseline_split_seed']} baseline F1 ({f4(ev['f1'])}) {position}, so the multi-split mean is the better summary of expected performance.",
              "", "Latency is end-to-end on CPU (image load, preprocessing, feature extraction, scoring and closest-reference retrieval) and varies with machine load. "
              "These are results on a small single-category benchmark, not production performance. Full experiment results: [docs/EXPERIMENTS.md](docs/EXPERIMENTS.md).", "", END]
    return "\n".join(lines)

def experiments_doc(e1: dict, e2: dict, e3: dict, e4: dict) -> str:
    out = ["# Experiments", "", "<!-- Generated by scripts/build_docs.py from reports/experiments/*.json. Do not edit by hand. -->", "",
           f"All experiments use the MVTec AD cable split ({e1['normal_train_images']} normal training images, {e1['test_images']} test images) and the unchanged method: "
           "ResNet18 `layer3` patches, Euclidean 1-NN to a normal-only bank, 95th-percentile image score, threshold at the 99th percentile of normal validation scores. "
           f"Protocol: {e1['protocol']}.", "",
           "**Latency in this file** measures nearest-neighbour scoring only (features are precomputed), so it is not comparable with the end-to-end latency in the README.", ""]

    out += ["## 1. Reference-bank size", "", f"Changed variable: {e1['changed_variable']}. Banks are nested prefixes of one permutation (sampling seed {e1['runs'][0]['sampling_seed']}); the threshold is recalibrated for each size.", "",
            table(["Patch cap", "Threshold", "Precision", "Recall", "F1", "ROC-AUC", "Confusion matrix", "Scoring latency (ms)"],
                  [[f"{r['patch_cap']:,}", f4(r["threshold"]), f4(r["precision"]), f4(r["recall"]), f4(r["f1"]), f4(r["roc_auc"]), cm(r["confusion_matrix"]), ms(r["average_latency_ms"])] for r in e1["runs"]]), "",
            "Note: the 30,000 row is **not** the recorded baseline. The baseline samples its 30,000 patches with the seed-42 generator that also made the split; this experiment uses a separate nested permutation, so the thresholds and metrics differ.", ""]

    out += ["## 2. Image-score aggregation", "", f"Changed variable: {e2['changed_variable']}. Uses the recorded baseline bank (artifact schema v{e2['reference_artifact_format_version']}); the threshold is recalibrated per percentile on the normal validation split.", "",
            table(["Patch-score percentile", "Threshold", "Precision", "Recall", "F1", "ROC-AUC", "Confusion matrix"],
                  [[f"{r['patch_score_percentile']:g}", f4(r["threshold"]), f4(r["precision"]), f4(r["recall"]), f4(r["f1"]), f4(r["roc_auc"]), cm(r["confusion_matrix"])] for r in e2["runs"]]), "",
            "The 95th-percentile row reproduces the recorded baseline exactly.", ""]

    agg = e3["aggregate"]
    out += ["## 3. Split stability", "", f"Changed variable: {e3['changed_variable']}. Each seed re-draws the 80/20 normal reference/validation split and the 30,000-patch bank.", "",
            table(["Seed", "Threshold", "Precision", "Recall", "F1", "ROC-AUC", "Confusion matrix"],
                  [[str(r["seed"]), f4(r["threshold"]), f4(r["precision"]), f4(r["recall"]), f4(r["f1"]), f4(r["roc_auc"]), cm(r["confusion_matrix"])] for r in e3["runs"]]), "",
            table(["Metric", "Mean", "Std", "Min", "Max"], [[k, f4(v["mean"]), f4(v["std"]), f4(v["min"]), f4(v["max"])] for k, v in agg.items() if k in ("threshold", "precision", "recall", "f1", "roc_auc")]), "",
            "The recorded seed-42 baseline is not one of these seeds; compare its F1 and recall in the README against the minimum above.", ""]

    out += ["## 4. Input-condition robustness and failure analysis", "", f"Changed variable: {e4['changed_variable']}. The baseline bank and threshold (`{e4['baseline_threshold']}`) are frozen (threshold_recalibrated: {str(e4['threshold_recalibrated']).lower()}).", "",
            table(["Condition", "Precision", "Recall", "F1", "ROC-AUC", "Confusion matrix"],
                  [[r["condition"], f4(r["precision"]), f4(r["recall"]), f4(r["f1"]), f4(r["roc_auc"]), cm(r["confusion_matrix"])] for r in e4["runs"]]), "",
            "### Per-category outcome (original images)", "",
            "Defect categories contain only anomalous images, so only the detection rate is meaningful there; the good category reports normal acceptance.", "",
            table(["Category", "Images", "Detected / false positives", "Rate"],
                  [[k, str(v["images"]), f"{v['detected']} detected" if "detected" in v else f"{v['false_positives']} false positives", f"{f4(v['detection_rate'])} detection" if "detection_rate" in v else f"{f4(v['normal_acceptance_rate'])} acceptance"]
                   for k, v in e4["per_category_original"].items()]), ""]
    fns = e4["false_negatives_original"]; margins = [fn["margin_to_threshold"] for fn in fns]
    counts: dict[str, int] = {}
    for fn in fns: counts[fn["category"]] = counts.get(fn["category"], 0) + 1
    out += [f"{len(fns)} false negatives: " + ", ".join(f"{k} {v}" for k, v in sorted(counts.items(), key=lambda kv: (-kv[1], kv[0]))) +
            f". Their scores fall {margins and f4(min(margins))}–{margins and f4(max(margins))} below the threshold.", "",
            f"Limitation: {e4['limitations']}", ""]
    return "\n".join(out)

def render() -> dict[Path, str]:
    ev = load(REPORTS_DIR / "evaluation.json"); meta = load(ARTIFACTS_DIR / "metadata.json") if (ARTIFACTS_DIR / "metadata.json").exists() else None
    e1, e2, e3, e4 = (load(EXP / f"{name}.json") for name in ("exp_01_reference_bank_size", "exp_02_score_aggregation", "exp_03_split_stability", "exp_04_robustness_failure_analysis"))
    readme = README.read_text(encoding="utf-8")
    if START not in readme or END not in readme: raise SystemExit("README.md is missing the generated results markers.")
    head, rest = readme.split(START, 1); tail = rest.split(END, 1)[1]
    return {README: head + readme_section(ev, meta, e3) + tail, EXPERIMENTS_DOC: experiments_doc(e1, e2, e3, e4)}

def main() -> None:
    parser = argparse.ArgumentParser(); parser.add_argument("--check", action="store_true"); args = parser.parse_args()
    outputs = render()
    if args.check:
        stale = [str(path.relative_to(ROOT)) for path, text in outputs.items() if not path.exists() or path.read_text(encoding="utf-8") != text]
        if stale: raise SystemExit("Out of date with reports: " + ", ".join(stale))
        print("Docs match the recorded reports."); return
    for path, text in outputs.items(): path.parent.mkdir(parents=True, exist_ok=True); path.write_text(text, encoding="utf-8"); print(path.relative_to(ROOT))

if __name__ == "__main__": main()
